"""Generate separate fidelity matrices for every preserved real codec key."""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = Path(__file__).resolve().parent


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def experiment(name: str, datasets: list[str], methods: list[dict], fidelity: str,
               profiles: list[tuple[str, int]], error_bound: str | None = None,
               dzip_runtime_preload: str | None = None) -> str:
    lines = ["# Generated by generate_experiments.py; inputs are development fixtures.",
             'schema = "tsbench.experiment/1"', f"name = {quoted(name)}",
             f"output = {quoted('../../runs/' + name + '-20261013')}", ""]
    for data in datasets:
        lines.extend(["[[datasets]]", f"id = {quoted(data)}", 'format = "npy"',
                      f"path = {quoted('data/' + data + '.npy')}", 'component = "V"', ""])
    for method in methods:
        lines.extend(["[[methods]]", f"id = {quoted(method['codec'])}", f"codec = {quoted(method['codec'])}"])
        if method.get("params"):
            params = ", ".join(f"{key} = {quoted(str(value))}" for key, value in method["params"].items())
            lines.append("params = { " + params + " }")
        lines.append("")
    lines.extend(["[task]", 'kind = "values"', f"fidelity = {quoted(fidelity)}",
                  'boundary = "object_memory"', 'lifecycle = "independent_object"', 'cache_policy = "natural"'])
    if error_bound is not None:
        lines.append(f"error_bound = {quoted(error_bound)}")
    lines.append("")
    for profile, threads in profiles:
        lines.extend(["[[profiles]]", f"id = {quoted(profile)}", 'device = "cpu"',
                      f"native_threads = {threads}", 'object_workers = 1'])
        if threads == 3 and dzip_runtime_preload:
            lines.append(f'runtime_preload = [{quoted(dzip_runtime_preload)}]')
        lines.append('')
    lines.extend(["[execution]", "sessions = 1", "rounds = 7", "warmup_objects = 2", "seed = 20261013",
                  "timeout_s = 120", "qualification_cache = true", "", "[analysis]",
                  'summary = "median_iqr"', 'inference = "none"', ""])
    return "\n".join(lines)


def generate(dzip_runtime_preload: str | None = None) -> list[Path]:
    cards = []
    for path in sorted((ROOT / "registry/codecs").glob("*.json")):
        card = json.loads(path.read_text())
        if "key" in card and card.get("identity", {}).get("family") != "HARNESS_ORACLE" and card.get("admission", {}).get("status") != "EXCLUDED":
            cards.append(card)
    if not cards or len({card["key"] for card in cards}) != len(cards):
        raise ValueError("registry must contain unique real codec keys")
    # Gorilla consumes paired timestamps and values. Its dedicated records
    # experiment preserves that contract; this matrix projects values only.
    lossless = [{"codec": "raw-store"}] + [{"codec": card["key"]} for card in cards
                                              if card["semantics"]["loss_modes"] == ["LOSSLESS"]
                                              and card["key"] != "gorilla-prometheus-xor"]
    definitions = {
        "all_lossless.toml": experiment("all-lossless", ["float64", "float32", "int16", "uint8", "symbols4", "uint32"],
                                        lossless, "bitwise", [("cpu-single", 1), ("cpu-dzip-three", 3)]),
        "bounded_quality.toml": experiment("bounded-quality", ["float64", "float32", "noise64"],
                                           [{"codec": key, "params": {"error_bound": "0.01"}}
                                            for key in ("serf-qt", "serf-xor", "zfp-accuracy-1d")],
                                           "bounded_abs", [("cpu-single", 1)], "0.01"),
        "empirical_quality.toml": experiment("empirical-quality", ["float64", "noise64"],
                                             [{"codec": "abba"}, {"codec": "fabba"}],
                                             "empirical_quality", [("cpu-single", 1)]),
    }
    if dzip_runtime_preload:
        preload = Path(dzip_runtime_preload).expanduser().resolve(strict=True)
        definitions['all_lossless_runtime.toml'] = experiment(
            'all-lossless-explicit-runtime', ['float64', 'float32', 'int16', 'uint8', 'symbols4', 'uint32'],
            lossless, 'bitwise', [('cpu-single', 1), ('cpu-dzip-three', 3)], dzip_runtime_preload=str(preload))
    paths = []
    for name, content in definitions.items():
        path = EXAMPLES / name
        path.write_text(content, encoding="utf-8")
        paths.append(path)
    return paths


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dzip-runtime-preload', help='Explicit existing libstdc++ path for the DZip profile only')
    arguments = parser.parse_args()
    for path in generate(arguments.dzip_runtime_preload):
        print(path)
